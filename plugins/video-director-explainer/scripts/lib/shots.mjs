// Screenshots of a video: the manifest (<videoDir>/shots.json), the images in
// public/shots/, and the module the Screenshot scene reads its boxes from.
import { createHash } from "node:crypto";
import { spawnSync } from "node:child_process";
import { existsSync, readFileSync, renameSync, writeFileSync } from "node:fs";
import path from "node:path";
import { die, readJson, requireFfmpeg, slash, writeJson } from "./common.mjs";

export const SHOTS_FILE = "shots.json";
/** The fill of a mask: solid, never a blur (blurred or pixelated text can be read back). */
export const MASK_COLOR = "#5f6368";
const NAME = /^[a-z0-9][a-z0-9-]{0,47}$/;

export const checkName = (name, what = "name") => {
  if (!NAME.test(String(name ?? ""))) die(`${what} "${name}": lowercase letters, digits and dashes, at most 48`);
  return name;
};

/** A name from a file name: "01 Open the café view.JPG" -> "01-open-the-cafe-view". */
export const nameFromFile = (file) =>
  path
    .basename(file, path.extname(file))
    .normalize("NFD")
    .replace(/[̀-ͯ]/g, "")
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, "-")
    .replace(/^-+|-+$/g, "")
    .slice(0, 48) || "shot";

export const loadShots = (videoDir) => {
  const file = path.join(videoDir, SHOTS_FILE);
  const data = existsSync(file) ? readJson(file) : {};
  return { shots: data.shots ?? {} };
};

export const saveShots = (videoDir, data) => {
  writeJson(path.join(videoDir, SHOTS_FILE), data);
  writeShotModule(videoDir, data);
};

/** The manifest entry of a scene's `src` ("shots/<name>.png"), or null. */
export const shotOfSrc = (data, src) => Object.values(data.shots).find((s) => s.file === src) ?? null;

/**
 * src/shots.generated.ts: size and boxes of every image, keyed by its `src`.
 * Rewritten by shots.mjs, the lint and the render, like the icon module.
 */
export const writeShotModule = (videoDir, data = loadShots(videoDir)) => {
  const entries = Object.values(data.shots)
    .sort((a, b) => a.file.localeCompare(b.file))
    .map((s) => {
      const boxes = Object.entries(s.boxes ?? {}).map(([k, b]) => `${JSON.stringify(k)}: ${JSON.stringify(b.box)}`);
      return `  ${JSON.stringify(s.file)}: { size: ${JSON.stringify(s.size)}, boxes: { ${boxes.join(", ")} } },`;
    });
  const lines = [
    "// Generated by the video-director-explainer scripts from shots.json (shots, lint, render).",
    "// Do not edit: use shots.mjs to change an image, a box or a mask.",
    "export type ShotBox = [number, number, number, number];",
    "export const shots: Record<string, { size: [number, number]; boxes: Record<string, ShotBox> }> = {",
    ...entries,
    "};",
    "",
  ];
  const out = path.join(videoDir, "src", "shots.generated.ts");
  const text = lines.join("\n");
  const old = existsSync(out) ? readFileSync(out, "utf8") : "";
  if (old !== text) writeFileSync(out, text, "utf8");
  return entries.length;
};

export const sha256 = (file) => createHash("sha256").update(readFileSync(file)).digest("hex");

/** Pixel size of an image, read with ffprobe. */
export const imageSize = (file) => {
  const { ffprobe } = requireFfmpeg();
  const r = spawnSync(ffprobe, ["-v", "error", "-select_streams", "v:0", "-show_entries", "stream=width,height", "-of", "csv=p=0:s=x", file], {
    encoding: "utf8",
    windowsHide: true,
  });
  const m = String(r.stdout ?? "").trim().match(/^(\d+)x(\d+)/);
  if (!m) die(`cannot read the size of ${slash(file)} (is it an image?)`, 1);
  return [Number(m[1]), Number(m[2])];
};

/**
 * Write `src` to `out` as PNG, with every box in `masks` filled solid. The
 * masks are drawn into the pixels: the stills, the contact sheets and the
 * page never hold what is under them.
 */
export const writePng = (src, out, masks = []) => {
  const { ffmpeg } = requireFfmpeg();
  const color = `0x${MASK_COLOR.slice(1)}@1`;
  const boxes = masks.map(([x, y, w, h]) => `drawbox=x=${Math.round(x)}:y=${Math.round(y)}:w=${Math.round(w)}:h=${Math.round(h)}:color=${color}:t=fill`);
  const tmp = `${out}.tmp.png`;
  const r = spawnSync(ffmpeg, ["-v", "error", "-y", "-i", src, ...(boxes.length ? ["-vf", boxes.join(",")] : []), "-frames:v", "1", "-update", "1", tmp], {
    encoding: "utf8",
    windowsHide: true,
  });
  if (r.status !== 0) die(`ffmpeg could not write ${slash(out)}: ${String(r.stderr).trim().split("\n").pop()}`, 1);
  // Rename over the old file only once the new one is whole.
  renameSync(tmp, out);
  return out;
};

/** "x,y,w,h" -> [x, y, w, h] inside an image of `size`. */
export const parseBox = (text, size, what = "box") => {
  const box = String(text).split(",").map((v) => Number(v.trim()));
  if (box.length !== 4 || box.some((v) => !Number.isFinite(v)) || box[2] <= 0 || box[3] <= 0) die(`${what} "${text}": write x,y,w,h in image pixels`);
  if (size && (box[0] < 0 || box[1] < 0 || box[0] + box[2] > size[0] || box[1] + box[3] > size[1])) {
    die(`${what} ${box.join(",")} is outside the image (${size[0]}x${size[1]})`);
  }
  return box;
};
