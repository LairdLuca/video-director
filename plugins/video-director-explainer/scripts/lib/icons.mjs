// Icons used by a storyboard -> src/icons.generated.ts with one static import
// each. Importing the whole Lucide set put several MB of JavaScript in every
// page that renders a still; one lazy chunk per icon made bundling slow.
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import path from "node:path";

/** Lucide file name: "server", "file-code"; PascalCase ("ShoppingCart") is accepted too. */
export const iconFile = (name) =>
  String(name)
    .trim()
    .replace(/([a-z0-9])([A-Z])/g, "$1-$2")
    .replace(/([a-zA-Z])([0-9])/g, "$1-$2")
    .replace(/[_\s]+/g, "-")
    .toLowerCase();

/** Every string under a key named "icon", anywhere in the shots' props. */
export const collectIcons = (storyboard) => {
  const found = new Set();
  const walk = (v) => {
    if (Array.isArray(v)) v.forEach(walk);
    else if (v && typeof v === "object") {
      for (const [k, x] of Object.entries(v)) {
        if (k === "icon" && typeof x === "string" && x.trim()) found.add(x);
        else walk(x);
      }
    }
  };
  for (const shot of storyboard?.shots ?? []) walk(shot.props);
  return [...found];
};

/**
 * Write src/icons.generated.ts for the icons the storyboard uses. Returns
 * { written, missing }: names whose file is not in the installed Lucide.
 * The file is rewritten only when its content changes.
 */
export const writeIconModule = (videoDir, storyboard) => {
  const dir = path.join(videoDir, "node_modules", "lucide-react", "dist", "esm", "icons");
  const names = collectIcons(storyboard);
  const missing = [];
  const files = new Map();
  for (const n of names) {
    const f = iconFile(n);
    if (existsSync(dir) && !existsSync(path.join(dir, `${f}.mjs`))) missing.push(n);
    else files.set(f, n);
  }
  const sorted = [...files.keys()].sort();
  const ident = (f) => `I_${f.replace(/-/g, "_")}`;
  const lines = [
    "// Generated by the video-director-explainer scripts from storyboard.json (lint, stills, freeze, render).",
    "// Do not edit: run lint-storyboard again after changing the icons in the storyboard.",
    'import type { LucideIcon } from "lucide-react";',
    ...sorted.map((f) => `import ${ident(f)} from "lucide-react/dist/esm/icons/${f}.mjs";`),
    "",
    "export const icons: Record<string, LucideIcon> = {",
    ...sorted.map((f) => `  "${f}": ${ident(f)},`),
    "};",
    "",
  ];
  const out = path.join(videoDir, "src", "icons.generated.ts");
  const text = lines.join("\n");
  const old = existsSync(out) ? readFileSync(out, "utf8") : "";
  if (old !== text) writeFileSync(out, text, "utf8");
  return { written: old !== text, missing, icons: sorted };
};
